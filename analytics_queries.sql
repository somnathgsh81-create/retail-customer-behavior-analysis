---- Total revenue by men and women-----
SELECT GENDER,
SUM(PURCHASE_AMOUNT) AS REVENUE
FROM CUSTOMER_ANALYSIS_TABLE
GROUP BY GENDER

------------CUSTOMER WHO USED DISCOUNT BUT SPENT MORE THAN AVERAGE PURCHASE AMOUNT-----------
SELECT CUSTOMER_ID,
PURCHASE_AMOUNT
FROM CUSTOMER_ANALYSIS_TABLE
WHERE DISCOUNT_APPLIED = 'Yes'
AND PURCHASE_AMOUNT > (SELECT AVG(PURCHASE_AMOUNT) FROM CUSTOMER_ANALYSIS_TABLE)

-----------TOP 5 PRODUCTS WITH HIGHEST AVERAGE REVIEW RATING---------------
WITH TOP_PROD AS (SELECT ITEM_PURCHASED,
ROUND(AVG(REVIEW_RATING),2) AS AVERAGE_RATING,
DENSE_RANK() OVER (ORDER BY AVG(REVIEW_RATING) DESC) AS RNK
FROM CUSTOMER_ANALYSIS_TABLE
GROUP BY ITEM_PURCHASED)

SELECT ITEM_PURCHASED,
AVERAGE_RATING
FROM TOP_PROD
WHERE RNK <=5


-------------COMPARE PURCHASE AMOUNT BETWEEN STANDARD AND EXPRESS SHIPPING------------
SELECT SHIPPING_TYPE,
ROUND(AVG(PURCHASE_AMOUNT),2) AS AVERAGE_AMOUNT
FROM CUSTOMER_ANALYSIS_TABLE
WHERE SHIPPING_TYPE IN ('Standard','Express')
GROUP BY SHIPPING_TYPE


-------------COMPARING AVERAGE SPEND AND REVENUE BETWEEN SUBSCRIBERS AND NON SUBSCRIBERS---------------
SELECT CONVERT(DECIMAL(10,2),AVG(PURCHASE_AMOUNT)) AS AVG_SPEND,
SUBSCRIPTION_STATUS,
COUNT(CUSTOMER_ID) AS TOTAL_CUSTOMER,
SUM(PURCHASE_AMOUNT) AS TOTAL_REVENUE
FROM CUSTOMER_ANALYSIS_TABLE
WHERE SUBSCRIPTION_STATUS IN ('Yes','No')
GROUP BY SUBSCRIPTION_STATUS

--------------------TOP 5 PRODUCTS WITH HIGHEST PERCENTAGE OF PURCHASES WITH DISCOUNT APPLIED--------------------
SELECT TOP 5
    ITEM_PURCHASED,
    CONVERT(DECIMAL(10,2), SUM(CASE WHEN DISCOUNT_APPLIED = 'Yes' THEN 1.0 ELSE 0.0 END) / COUNT(*)) AS DISCOUNT_RATE
FROM CUSTOMER_ANALYSIS_TABLE
GROUP BY ITEM_PURCHASED

---------------------SEGMENT CUSTOMERS BASED ON LOYAL, NEW AND RETURNING BASED ON TOTAL NUMBER OF PREVIOUS PURCHASES AND COUNT OF EACH SEGMENT-----
WITH CUST_TYPE AS (
SELECT CUSTOMER_ID,
PREVIOUS_PURCHASES,
CASE 
WHEN PREVIOUS_PURCHASES = 1 THEN 'NEW'
WHEN PREVIOUS_PURCHASES >=2 AND PREVIOUS_PURCHASES <=10 THEN 'RETURNING'
ELSE 'LOYAL' END AS CUSTOMER_SEGMENT
FROM CUSTOMER_ANALYSIS_TABLE)

SELECT CUSTOMER_SEGMENT, 
COUNT(*) AS NO_OF_CUSTOMERS
FROM CUST_TYPE
GROUP BY CUSTOMER_SEGMENT

-------------------------TOP 3 MOST PURCHASED PRODUCT IN EACH CATEGORY---------------------

WITH TOT_PROD AS (SELECT ITEM_PURCHASED,
CATEGORY,
COUNT(CUSTOMER_ID) AS TOT_ORDER,
DENSE_RANK() OVER(PARTITION BY CATEGORY ORDER BY COUNT(CUSTOMER_ID) DESC) AS RNK
FROM CUSTOMER_ANALYSIS_TABLE
GROUP BY ITEM_PURCHASED,CATEGORY)

SELECT DISTINCT
CATEGORY,
TOT_ORDER,
RNK AS RANK
FROM TOT_PROD
WHERE RNK <=3

--------------------- CHECK WHETHER CUSTOMERS WHO ARE REPEAT BUYERS ALSO SUBSCRIBE------------------
SELECT 
COUNT(*) TOTAL_CUSTOMER,
SUBSCRIPTION_STATUS
FROM CUSTOMER_ANALYSIS_TABLE
WHERE  PREVIOUS_PURCHASES >5
GROUP BY SUBSCRIPTION_STATUS


-------------------REVENUE AS PER AGE GROUP--------------------
SELECT
SUM(PURCHASE_AMOUNT) AS REVENUE,
AGE_GROUP
FROM CUSTOMER_ANALYSIS_TABLE
GROUP BY  AGE_GROUP
ORDER BY REVENUE DESC
